export function getTopicGroups(section) {
  return TOPICS[section] ?? [];
}

export function getTopicMeta(section, topic) {
  return getTopicGroups(section).find((item) => item.slug === topic);
}

export function getPostTopic(id) {
  const parts = id.split('/');
  return parts.length > 2 ? parts[1] : undefined;
}

export const nestedPostRoutes = Object.fromEntries(
  Object.entries(TOPICS).flatMap(([section, topics]) =>
    topics.flatMap((topic) =>
      topic.posts.map((slug) => [
        `/${section}/${slug}`,
        `/${section}/${topic.slug}/${slug}`,
      ]),
    ),
  ),
);
